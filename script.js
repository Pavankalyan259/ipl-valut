// Simple frontend-only authentication demo.
// It does NOT provide real Google OAuth or SMS OTP verification.
const authModal = document.querySelector("#auth-modal");
const authBtn = document.querySelector("#auth-btn");
const authForm = document.querySelector("#auth-form");
const authTitle = document.querySelector("#auth-title");
const authSubmit = document.querySelector("#auth-submit");
const authNameField = document.querySelector("#name-field");
const authMessage = document.querySelector("#auth-message");
let authMode = "signin";

function getUsers(){ return JSON.parse(localStorage.getItem("iplVaultUsers") || "[]"); }
function saveUsers(users){ localStorage.setItem("iplVaultUsers", JSON.stringify(users)); }

function openAuth(mode="signin"){
  authMode = mode;
  authModal.classList.remove("hidden");
  document.body.style.overflow="hidden";
  authMessage.textContent="";
  document.querySelectorAll(".auth-tab").forEach(t=>t.classList.toggle("active",t.dataset.authTab===mode));
  authTitle.textContent = mode==="signin" ? "Sign in" : "Create account";
  authSubmit.textContent = mode==="signin" ? "Sign in" : "Register";
  authNameField.classList.toggle("hidden", mode!=="register");
}
function closeAuth(){authModal.classList.add("hidden");document.body.style.overflow="";}
function updateAuthButton(){
  const current = localStorage.getItem("iplVaultCurrentUser");
  authBtn.textContent = current ? `Hi, ${current} · Sign out` : "Sign in";
}
authBtn.addEventListener("click",()=>{
  const current=localStorage.getItem("iplVaultCurrentUser");
  if(current){localStorage.removeItem("iplVaultCurrentUser");updateAuthButton();}
  else openAuth("signin");
});
document.querySelectorAll("[data-auth-close]").forEach(el=>el.addEventListener("click",closeAuth));
document.querySelectorAll("[data-auth-tab]").forEach(tab=>tab.addEventListener("click",()=>openAuth(tab.dataset.authTab)));
authForm.addEventListener("submit",e=>{
  e.preventDefault();
  const name=document.querySelector("#auth-name").value.trim();
  const mobile=document.querySelector("#auth-mobile").value.trim();
  const email=document.querySelector("#auth-email").value.trim().toLowerCase();
  const password=document.querySelector("#auth-password").value;
  if(!mobile && !email){authMessage.textContent="Enter a mobile number or Gmail address.";return;}
  if(mobile && !/^\d{10}$/.test(mobile)){authMessage.textContent="Enter a valid 10-digit mobile number.";return;}
  if(email && (!email.endsWith("@gmail.com") || !email.includes("@"))){authMessage.textContent="Please use a Gmail address.";return;}
  if(password.length<6){authMessage.textContent="Password must contain at least 6 characters.";return;}
  const users=getUsers();
  const key=mobile || email;
  if(authMode==="register"){
    if(!name){authMessage.textContent="Enter your name.";return;}
    if(users.some(u=>u.key===key)){authMessage.textContent="An account already exists for this login.";return;}
    users.push({key,name,mobile,email,password});
    saveUsers(users);
    localStorage.setItem("iplVaultCurrentUser",name);
    closeAuth(); updateAuthButton();
    alert(`Welcome to IPL Vault, ${name}!`);
  }else{
    const user=users.find(u=>u.key===key && u.password===password);
    if(!user){authMessage.textContent="Account not found or password is incorrect.";return;}
    localStorage.setItem("iplVaultCurrentUser",user.name);
    closeAuth(); updateAuthButton();
    alert(`Welcome back, ${user.name}!`);
  }
});
updateAuthButton();
